public class DoWhileLoop {
    public static void main(String[] args) {
        int i = 1;
        do{
            System.out.println(i);
            i++;
        }while(i <= 100);
        // if we change the value of i to 100 then it will print only 100.
        // if we change the value of i to 101 then it will not print anything because
        int  x = -30;
        do{
            System.out.println("HI");
            x++;
        }while(x >= -25 );
    }
}
