public class ForLoop {
    public static void main(String[] args) {
        int i;
        
        for( i = 1; i <= 10; i = i + 1) { // if we increase the value of i by 2 then it will print only odd numbers.
            System.out.println(i);

            // so what if we use break?
            if(i == 5){
                break; // it will stop the loop when i is equal to 5.
                // so what if we use continue?
            }else if(i == 3){
                continue; // it will skip the iteration when i is equal to 3.
                
                
                }
                   
            }

        }
    }


